/** 음성 답변을 TTS 에 넣기 전에 소리로 읽을 수 없는 잔여물을 걷어낸다. */
export function stripForSpeech(text: string): string {
  return text
    .replace(/```[\s\S]*?```/g, ' ')          // 코드블록
    .replace(/[*_`#>|]/g, '')                  // 마크다운 기호
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')   // 링크 → 라벨만
    .replace(/^\s*[-•]\s*/gm, '')              // 글머리표
    .replace(/([0-9.]+)\s*°C/g, '$1도')        // 단위를 말로
    .replace(/([0-9.]+)\s*%/g, '$1퍼센트')
    .replace(/\s+/g, ' ')
    .trim();
}
